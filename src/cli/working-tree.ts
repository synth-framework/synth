/**
 * Inspect the git working tree and return whether it is dirty along with the
 * porcelain status text. Non-git directories are treated as clean so the CLI
 * can still operate outside version control.
 */
export async function getWorkingTreeStatus(): Promise<{ dirty: boolean; status: string }> {
  return new Promise((resolve) => {
    const child = spawn("git", ["status", "--porcelain"], { cwd: process.cwd() })
    let stdout = ""
    child.stdout.on("data", (data: Buffer) => {
      stdout += data.toString("utf-8")
    })
    child.on("close", (code) => {
      // Trim only trailing whitespace; leading whitespace is part of the
      // porcelain format (e.g. " M filename" for unstaged modifications).
      const status = stdout.replace(/\s+$/, "")
      resolve({ dirty: code === 0 && status.length > 0, status })
    })
    child.on("error", () => resolve({ dirty: false, status: "" }))
  })
}

export async function isWorkingTreeDirty(): Promise<boolean> {
  return (await getWorkingTreeStatus()).dirty
}

/**
 * Run a git command to completion. Resolves when the command exits 0 and
 * rejects with the captured stderr otherwise.
 */
export function runGitSpawn(args: string[]): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn("git", args, { cwd: process.cwd() })
    let stderr = ""
    child.stderr.on("data", (data: Buffer) => { stderr += data.toString("utf-8") })
    child.on("close", (code) => {
      if (code !== 0) reject(new Error(stderr.trim() || `git ${args[0]} exited with code ${code}`))
      else resolve()
    })
    child.on("error", reject)
  })
}

/**
 * Return the paths of untracked source files in the working tree, excluding
 * derived SYNTH state. Uses `--untracked-files=all` so files nested in
 * otherwise-untracked directories are listed individually. Outside git or on
 * git errors an empty list is returned so evidence capture degrades gracefully.
 */
export async function getUntrackedSourcePaths(): Promise<string[]> {
  return new Promise((resolve) => {
    const child = spawn("git", ["status", "--porcelain", "--untracked-files=all"], { cwd: process.cwd() })
    let stdout = ""
    child.stdout.on("data", (data: Buffer) => { stdout += data.toString("utf-8") })
    child.on("close", (code) => {
      if (code !== 0) {
        resolve([])
        return
      }
      const paths = stdout
        .split("\n")
        .filter((line) => line.startsWith("?? "))
        .map((line) => line.slice(3))
        .filter((p) => !isGovernedArtifact(p))
      resolve(paths)
    })
    child.on("error", () => resolve([]))
  })
}

// ============================================================
// EXP-AUTO-COMMIT-001: Auto-commit derived SYNTH state
// ============================================================
// Derived SYNTH state (.synth/data/, proof/expeditions/, event log,
// canonical state, AGENTS.md) is generated by lifecycle transitions.
// These files should never block expedition completion, and they should
// be checkpointed automatically so agents do not have to commit them
// manually between steps.
// ============================================================

// Auto-commit scope and exclusions come from the artifact policy
// (src/state/artifact-policy.ts). The include roots are directory pathspecs:
// `git add -A -- <dir>` stages additions, modifications and deletions, and
// never fails on ignored content the way an explicit file list does (audit D1).

/** Existing subset of the include roots (a missing pathspec fails `git add`). */
export async function existingAutoCommitPathspecs(cwd: string): Promise<string[]> {
  const existing: string[] = []
  for (const relPath of AUTO_COMMIT_INCLUDE_ROOTS) {
    try {
      await fs.access(path.join(cwd, relPath))
      existing.push(relPath)
    } catch {
      // path does not exist in this workspace
    }
  }
  return existing
}

/** True when `relPath` is in the index. */
export function isTrackedPath(cwd: string, relPath: string): boolean {
  try {
    const listing = execFileSync("git", ["ls-files", "--", relPath], { cwd, encoding: "utf-8" })
    return listing.trim().length > 0
  } catch {
    return false
  }
}

export type AutoCommitResult = {
  committed: boolean
  commitHash?: string
  message: string
  files: string[]
  reason?: string
}

export function isScratchFile(relPath: string): boolean {
  const lowercase = relPath.toLowerCase()
  return (
    relPath.startsWith("scratch") ||
    relPath.includes("/scratch") ||
    lowercase.endsWith(".log") ||
    lowercase.endsWith(".patch") ||
    lowercase.endsWith(".diff") ||
    lowercase.includes("evaluation") ||
    lowercase.includes("benchmark") ||
    lowercase.includes("audit-report")
  )
}

/** Governed artifacts and scratch files never count as source changes. */
export function isNonSourcePath(relPath: string): boolean {
  return isExcludedFromCompletionGate(relPath) || isScratchFile(relPath)
}

/**
 * Return the working-tree status limited to non-derived source files.
 * Derived state changes are excluded from the dirty flag so they cannot
 * block expedition completion, but they are reported separately so callers
 * can decide to auto-commit them.
 */
export async function getNonDerivedWorkingTreeStatus(): Promise<{
  dirty: boolean
  status: string
  derivedOnly: boolean
  derivedStatus: string
  suggestedCommit?: string
}> {
  const { dirty, status } = await getWorkingTreeStatus()
  if (!dirty) {
    return { dirty: false, status, derivedOnly: false, derivedStatus: "" }
  }
  const allLines = status.split("\n").filter((line) => line.length >= 3)
  const derivedLines: string[] = []
  const nonDerivedLines: string[] = []
  for (const line of allLines) {
    const relPath = line.slice(3)
    if (isNonSourcePath(relPath)) {
      derivedLines.push(line)
    } else {
      nonDerivedLines.push(line)
    }
  }
  const filePaths = nonDerivedLines.map((line) => line.slice(3).trim())
  const suggestedCommit =
    filePaths.length > 0
      ? `git add ${filePaths.map((p) => JSON.stringify(p)).join(" ")} && git commit -m "expedition: describe source changes before completion"`
      : undefined
  return {
    dirty: nonDerivedLines.length > 0,
    status: nonDerivedLines.join("\n"),
    derivedOnly: nonDerivedLines.length === 0,
    derivedStatus: derivedLines.join("\n"),
    suggestedCommit,
  }
}

// `--no-auto-commit` is a global flag parsed once in main(); ceremonies run
// from the handleIntent choke point do not receive the per-command flags, so
// the parsed value is mirrored here.
let autoCommitDisabledByFlag = false

/** Set by the dispatcher when --no-auto-commit is passed. The flag lives here,
 *  next to isAutoCommitEnabled which reads it, so there is one authority for it;
 *  before the extraction it was a module-private `let` in synth.ts. */
export function setAutoCommitDisabledByFlag(disabled: boolean): void {
  autoCommitDisabledByFlag = disabled
}


export function isAutoCommitEnabled(flags?: Record<string, string | boolean>): boolean {
  if (autoCommitDisabledByFlag) return false
  if (flags && (flags["no-auto-commit"] === true || flags["no-auto-commit"] === "true")) {
    return false
  }
  const env = process.env.SYNTH_AUTO_COMMIT
  if (env === "0" || env === "false") return false
  return true
}

export async function collectDerivedStateFiles(cwd: string): Promise<string[]> {
  const files: string[] = []
  const dirs = [sdk.paths.dataDir(cwd), path.join(cwd, "proof", "expeditions")]
  const rootFiles = [
    sdk.paths.stateFile(cwd),
    path.join(cwd, "AGENTS.md"),
  ]

  for (const dir of dirs) {
    try {
      await fs.access(dir)
      await collectDerivedStateFilesRecursive(dir, cwd, files)
    } catch {
      // directory does not exist
    }
  }

  for (const file of rootFiles) {
    try {
      await fs.access(file)
      files.push(path.relative(cwd, file))
    } catch {
      // file does not exist
    }
  }

  return files
}

export async function collectDerivedStateFilesRecursive(dir: string, cwd: string, out: string[]) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      await collectDerivedStateFilesRecursive(fullPath, cwd, out)
    } else {
      out.push(path.relative(cwd, fullPath))
    }
  }
}

/**
 * Paths that .gitignore excludes, *including* tracked ones (`--no-index`).
 * Plain `git check-ignore` hides indexed paths — the root cause of audit D2:
 * the old filter never removed the ignored-but-tracked drafts from the
 * staging batch, so `git add` refused the whole list (D1).
 */
export async function listIgnoredPaths(cwd: string, files: string[]): Promise<Set<string>> {
  return new Promise((resolve) => {
    if (files.length === 0) {
      resolve(new Set())
      return
    }
    const child = spawn("git", ["check-ignore", "--no-index", "--stdin"], { cwd })
    let stdout = ""
    child.stdout.on("data", (data: Buffer) => {
      stdout += data.toString("utf-8")
    })
    child.on("close", (code) => {
      // git check-ignore exits 1 when none of the inputs are ignored.
      if (code !== 0 && code !== 1) {
        resolve(new Set())
        return
      }
      resolve(new Set(stdout.trim().split("\n").map((line) => line.trim()).filter(Boolean)))
    })
    child.on("error", () => resolve(new Set()))
    child.stdin.end(files.join("\n"))
  })
}

/** Auto-commit only ever stages committable artifacts (durable + input). */
export function isAutoCommitScoped(relPath: string): boolean {
  return isCommittableArtifact(relPath)
}

/**
 * Stage auto-commit content with a resilient three-step strategy:
 *   1. one `git add -A` over directory pathspecs (stages deletions too, and
 *      never fails because an ignored path was named explicitly);
 *   2. per-path adds, retrying ignored-but-tracked paths with `-f`;
 *   3. report the paths that still failed instead of aborting the commit.
 * Returns the staged paths within the auto-commit scope.
 */
export async function stageAutoCommitPaths(cwd: string): Promise<{ staged: string[]; failures: string[] }> {
  const failures: string[] = []
  const pathspecs = await existingAutoCommitPathspecs(cwd)

  let primaryOk = false
  if (pathspecs.length > 0) {
    try {
      execFileSync("git", ["add", "-A", "--", ...pathspecs, ...autoCommitExcludePathspecs()], {
        cwd,
        stdio: ["pipe", "pipe", "pipe"],
      })
      primaryOk = true
    } catch {
      // Fall back to per-path staging so one bad path cannot kill the commit.
    }
  }

  if (!primaryOk) {
    // Per-path fallback: ignored *and untracked* paths are never staged;
    // ignored *and tracked* paths are staged with `-f` (they are legitimate
    // content — e.g. draft inputs — and explicit pathspecs need the flag).
    const candidates = (await collectDerivedStateFiles(cwd)).filter((relPath) =>
      isAutoCommitScoped(relPath),
    )
    const ignored = await listIgnoredPaths(cwd, candidates)
    for (const relPath of candidates) {
      const isIgnored = ignored.has(relPath)
      if (isIgnored && !isTrackedPath(cwd, relPath)) continue
      const attempts = isIgnored ? [["-f"], []] : [[], ["-f"]]
      let staged = false
      for (const extra of attempts) {
        try {
          execFileSync("git", ["add", ...extra, "-A", "--", relPath], { cwd, stdio: ["pipe", "pipe", "pipe"] })
          staged = true
          break
        } catch {
          // try the next strategy
        }
      }
      if (!staged) failures.push(relPath)
    }
  }

  const stdout = execFileSync("git", ["diff", "--cached", "--name-only"], { cwd, encoding: "utf-8" })
  const staged = stdout
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && isAutoCommitScoped(line))
  return { staged, failures }
}

